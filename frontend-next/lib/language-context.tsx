interface LanguageContextType {
    language: Language;
    setLanguage: (langCode: string) => void;
    languages: Language[];
    t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
    const [language, setLanguageState] = useState<Language>(languages[0]);

    useEffect(() => {
        const savedLangCode = localStorage.getItem('language');
        if (savedLangCode) {
            const lang = languages.find(l => l.code === savedLangCode);
            if (lang) setLanguageState(lang);
        }
    }, []);

    const setLanguage = (langCode: string) => {
        const lang = languages.find(l => l.code === langCode);
        if (lang) {
            setLanguageState(lang);
            localStorage.setItem('language', langCode);
        }
    };

    const t = (key: string) => {
        return translations[language.code]?.[key] || key;
    };

    return (
        <LanguageContext.Provider value={{ language, setLanguage, languages, t }}>
            {children}
        </LanguageContext.Provider>
    );
}

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (context === undefined) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
}
